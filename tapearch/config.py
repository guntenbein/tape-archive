# --- кластеризация версий ---
CLUSTER_MIN_MUSIC_S = 25.0   # короче — в сравнение версий не берём
CLUSTER_PREFILTER_TOPK = 12  # сколько кандидатов на сегмент проверять DTW
# Порог ставится на АБСОЛЮТНОЕ совпадение, а не на долю сегмента. На пилоте
# доля давала перевёрнутый ответ: настоящие дубли песни совпадали 39-60 с с
# похожестью 0.98, но делились на длинный сегмент и не проходили, а болтовня
# под гитару совпадала 20-26 с с похожестью 0.80, делилась на короткий кусок и
# проходила. Длительность совпадения и похожесть разделяют эти случаи начисто.
CLUSTER_MIN_MATCH_S = 30.0     # столько секунд должно лечь в диагональ
CLUSTER_MIN_RUN_S = 20.0       # и хотя бы столько подряд, а не вразброс
CLUSTER_MIN_SIMILARITY = 0.93  # похожесть на совпавших кадрах
