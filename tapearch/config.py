SMOOTH_MEDIAN_S = 2.5        # медианное сглаживание покадровых вероятностей
MIN_SEGMENT_S = 2.0          # короче — приклеиваем к соседу
MIN_SILENCE_SEGMENT_S = 3.0  # пауза короче не заводит отдельную строку в отчёте
