# --- сегментация ---
SILENCE_OVER_FLOOR_DB = 5.0  # НАСТОЯЩАЯ тишина = шумовая полка файла + столько дБ
# Пауза — понятие относительное. На кассете фон гуляет по ленте на десятки дБ
# (разные комнаты, разные сессии, АРУ магнитофона): на пилоте 1996 года фон по
# пятиминуткам шёл -61, -23, -24, -11, -30, -30, -19 дБ. Абсолютный порог там
# не видит ни одной паузы между дублями, хотя на слух они очевидны. Поэтому
